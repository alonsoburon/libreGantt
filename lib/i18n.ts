type Dict = (typeof dict)[Lang];

interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLang = create<LangState>()(
  persist(
    (set) => ({
      lang: "es",
      setLang: (lang) => set({ lang }),
    }),
    { name: "gantt-lang" },
  ),
);

export function useT(): Dict {
  const lang = useLang((s) => s.lang);
  return dict[lang];
}
